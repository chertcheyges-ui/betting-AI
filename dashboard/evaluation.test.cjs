const assert=require('node:assert/strict');
const math=require('./dist/evaluation.js');
const dataset=rows=>math.validate({schema_version:1,kind:'synthetic_evaluation',observations:rows});
const close=(a,b)=>assert(Math.abs(a-b)<1e-12);
let scores=math.evaluate(dataset([{id:'perfect',probabilities:[1,0,0],actual:0}]));
close(scores.accuracy,1);close(scores.brier,0);close(scores.logloss,0);
scores=math.evaluate(dataset([{id:'wrong',probabilities:[1,0,0],actual:1}]));
close(scores.accuracy,0);close(scores.brier,2);assert.equal(scores.logloss,Infinity);
scores=math.evaluate(dataset([0,1,2].map(actual=>({id:String(actual),probabilities:[1/3,1/3,1/3],actual}))));
close(scores.accuracy,1/3);close(scores.brier,2/3);close(scores.logloss,Math.log(3));
for(const p of [[-1,1,1],[NaN,0,1],[0.2,0.2,0.2],[Infinity,0,0]])assert.throws(()=>dataset([{probabilities:p,actual:0}]));
assert.throws(()=>dataset([{probabilities:[0.5,0.3,0.2],actual:3}]));
assert.throws(()=>dataset([]));
const normal=math.generate(100,1),confident=math.generate(100,3);
assert.deepEqual(normal.observations.map(r=>r.actual),confident.observations.map(r=>r.actual));
assert.deepEqual(normal.observations.map(r=>math.score(r).predicted),confident.observations.map(r=>math.score(r).predicted));
assert.deepEqual(normal,math.generate(100,1));
assert.equal(normal.observations.length,100);
for(const r of normal.observations)close(r.probabilities.reduce((a,b)=>a+b),1);
assert(normal.observations.every(r=>r.home && r.away && r.home!==r.away));
assert.equal(math.validate(normal).observations[0].home,normal.observations[0].home);
for(const r of normal.observations)close(math.percentages(r.probabilities).reduce((a,b)=>a+b),100);
close(math.percentages([1/3,1/3,1/3]).reduce((a,b)=>a+b),100);
assert.throws(()=>math.generate(0,1));assert.throws(()=>math.generate(100,0));
assert.throws(()=>dataset([{id:'same',probabilities:[1,0,0],actual:0},{id:'same',probabilities:[1,0,0],actual:0}]));
console.log('PASS: perfect/wrong/uniform metrics, invalid inputs, repeatability, confidence comparison.');
